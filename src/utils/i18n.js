export function getTranslation(lang) {
  return translations[lang] || translations['English'];
}

export function useTranslation() {
  const [lang, setLang] = useState(() => (dataStore.getLanguage ? dataStore.getLanguage() : 'English'));

  useEffect(() => {
    const handleLangChange = () => {
      const current = dataStore.getLanguage ? dataStore.getLanguage() : 'English';
      setLang(current);
    };

    window.addEventListener('sahara:lang-change', handleLangChange);
    window.addEventListener('sahara:datastore-change', handleLangChange);

    return () => {
      window.removeEventListener('sahara:lang-change', handleLangChange);
      window.removeEventListener('sahara:datastore-change', handleLangChange);
    };
  }, []);

  return { t: getTranslation(lang), lang };
}
